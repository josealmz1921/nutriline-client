import { afterEach, describe, expect, it, vi } from 'vitest'
import { cleanup, fireEvent, render, screen, within } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import DietaryRecall from './DietaryRecall'
import { selectRecallOption, startRecallMeal } from './recallTestHelpers'

afterEach(cleanup)

describe('R24 dinámico con Informed', () => {
  it('valida el estado general, los cinco tiempos y las filas sin perder la captura al revisar', async () => {
    const user = userEvent.setup()
    const complete = vi.fn()
    render(<DietaryRecall onComplete={complete} />)
    await user.click(screen.getByRole('button', { name: 'Completar R24' }))
    expect(complete).not.toHaveBeenCalled()
    expect(document.activeElement).toBe(screen.getByRole('combobox', { name: 'Disponibilidad del recordatorio' }))
    await startRecallMeal(user)
    await user.click(screen.getByRole('button', { name: 'Completar R24' }))
    expect(complete).not.toHaveBeenCalled()
    const preparation = screen.getByLabelText('Nombre de preparación · Desayuno · Preparación 1')
    expect(document.activeElement).toBe(preparation)
    fireEvent.change(preparation, { target: { value: 'Desayuno ficticio' } })
    await selectRecallOption(user, 'Catálogo · Desayuno · Preparación 1 · Alimento 1', 'Manzana')
    const quantity = screen.getByLabelText('Cantidad · Desayuno · Preparación 1 · Alimento 1')
    fireEvent.change(quantity, { target: { value: '2' } })
    expect(within(screen.getByRole('region', { name: 'Nutrientes del recordatorio' })).getByText('110')).toBeTruthy()
    expect((screen.getByLabelText('Alimento · Desayuno · Preparación 1 · Alimento 1') as HTMLInputElement).value).toBe('Manzana')
    expect((screen.getByLabelText('Unidad · Desayuno · Preparación 1 · Alimento 1') as HTMLInputElement).value).toBe('pieza')
    await user.click(screen.getByRole('button', { name: 'Revisar recordatorio' }))
    const dialog = await screen.findByRole('dialog', { name: 'Revisar recordatorio' })
    expect(within(dialog).getByText('Desayuno ficticio')).toBeTruthy()
    expect(dialog.textContent).toContain('Manzana · 2 pieza')
    expect(within(dialog).getByText('110')).toBeTruthy()
    await user.click(within(dialog).getByRole('button', { name: 'Volver al recordatorio' }))
    expect((quantity as HTMLInputElement).value).toBe('2')
    await user.click(screen.getByRole('button', { name: 'Completar R24' }))
    expect(complete).toHaveBeenCalledOnce()
  })

  it('elimina alimentos y preparaciones con confirmación, sin desplazar datos a otra fila', async () => {
    const user = userEvent.setup()
    render(<DietaryRecall />)
    await startRecallMeal(user)
    fireEvent.change(screen.getByLabelText('Alimento · Desayuno · Preparación 1 · Alimento 1'), { target: { value: 'Primero ficticio' } })
    await user.click(screen.getByRole('button', { name: 'Agregar alimento · Desayuno · Preparación 1' }))
    fireEvent.change(screen.getByLabelText('Alimento · Desayuno · Preparación 1 · Alimento 2'), { target: { value: 'Segundo ficticio' } })
    await user.click(screen.getByRole('button', { name: 'Quitar alimento · Desayuno · Preparación 1 · Alimento 1' }))
    expect(screen.getByRole('button', { name: 'Conservar alimento' })).toBeTruthy()
    await user.click(screen.getByRole('button', { name: 'Confirmar eliminación de alimento' }))
    expect((screen.getByLabelText('Alimento · Desayuno · Preparación 1 · Alimento 1') as HTMLInputElement).value).toBe('Segundo ficticio')
    expect(screen.queryByLabelText('Alimento · Desayuno · Preparación 1 · Alimento 2')).toBeNull()
    await user.click(screen.getByRole('button', { name: 'Quitar preparación · Desayuno · Preparación 1' }))
    await user.click(screen.getByRole('button', { name: 'Conservar preparación' }))
    expect(screen.getByLabelText('Alimento · Desayuno · Preparación 1 · Alimento 1')).toBeTruthy()
    await user.click(screen.getByRole('button', { name: 'Quitar preparación · Desayuno · Preparación 1' }))
    await user.click(screen.getByRole('button', { name: 'Confirmar eliminación de preparación' }))
    expect(screen.queryByLabelText('Nombre de preparación · Desayuno · Preparación 1')).toBeNull()
  })

  it('excluye un borrador inválido al declarar ausencia, pero lo conserva al volver a capturar', async () => {
    const user = userEvent.setup()
    const complete = vi.fn()
    render(<DietaryRecall onComplete={complete} />)
    await startRecallMeal(user)
    fireEvent.change(screen.getByLabelText('Cantidad · Desayuno · Preparación 1 · Alimento 1'), { target: { value: '-9' } })
    await user.click(screen.getByRole('button', { name: 'Completar R24' }))
    await selectRecallOption(user, 'Disponibilidad del recordatorio', 'Recordatorio no disponible')
    await user.click(screen.getByRole('button', { name: 'Completar R24' }))
    expect(complete).toHaveBeenCalledOnce()
    await user.click(screen.getByRole('button', { name: 'Revisar recordatorio' }))
    const dialog = await screen.findByRole('dialog')
    expect(within(dialog).getByText(/Recordatorio no disponible/)).toBeTruthy()
    expect(dialog.textContent).not.toContain('-9')
    await user.click(within(dialog).getByRole('button', { name: 'Volver al recordatorio' }))
    await selectRecallOption(user, 'Disponibilidad del recordatorio', 'Capturar recordatorio')
    expect((screen.getByLabelText('Cantidad · Desayuno · Preparación 1 · Alimento 1') as HTMLInputElement).value).toBe('-9')
  })
})
