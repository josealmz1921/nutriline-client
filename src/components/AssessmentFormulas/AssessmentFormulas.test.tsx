import { afterEach, describe, expect, it } from 'vitest'
import { cleanup, fireEvent, render, screen, within } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import { MemoryRouter, Route, Routes } from 'react-router-dom'
import PatientRegistration from '../PatientRegistration'
import ConsultationRegistration from '../ConsultationRegistration'
import { consultationToRecall, consultationSkipRecall } from '../ConsultationRegistration/consultationTestHelpers'
import { continueToRecall } from '../PatientRegistration/assessmentTestHelpers'
import { selectRecallOption as selectOption } from '../DietaryRecall/recallTestHelpers'

afterEach(cleanup)
const progress = () => (screen.getByRole('progressbar', { name: 'Secciones completadas' }) as HTMLProgressElement).value
const selectMetabolicMethod = async (user: ReturnType<typeof userEvent.setup>) => {
  await selectOption(user, 'Disponibilidad de revisión de fórmulas', 'Revisar fórmulas y resultados')
  fireEvent.change(screen.getByLabelText('Fecha de referencia de fórmulas'), { target: { value: '2026-11-05' } })
  await selectOption(user, 'Sexo utilizado por las ecuaciones', 'Masculino (coeficientes de la ecuación)')
  await selectOption(user, 'Población y aplicabilidad de las ecuaciones', 'Adulto general · Aplicabilidad revisada por el profesional')
  await selectOption(user, 'Autor de metabolismo basal / reposo', 'Mifflin-St Jeor, 1990 · Versión simplificada')
}

describe('Seis pasos y revisión de fórmulas', () => {
  it('llega a 6/6 sin guardar, abre ambos reportes y revoca confirmaciones al editar sin perder selecciones', async () => {
    const user = userEvent.setup()
    render(<MemoryRouter><PatientRegistration /></MemoryRouter>)
    await continueToRecall(user)
    await selectOption(user, 'Disponibilidad del recordatorio', 'Recordatorio no realizado')
    await user.click(screen.getByRole('button', { name: 'Completar R24' }))
    expect(progress()).toBe(4)
    await user.click(screen.getByRole('button', { name: 'Continuar' }))
    expect(progress()).toBe(4)
    await selectOption(user, 'Disponibilidad de hábitos', 'Capturar entrevista de hábitos')
    await selectOption(user, 'Disponibilidad de actividad física', 'Sin actividad física (declarado)')
    fireEvent.change(screen.getByLabelText('Horas de sueño por día'), { target: { value: '7' } })
    await user.click(screen.getByRole('button', { name: 'Continuar' }))
    expect(progress()).toBe(5)
    await user.click(screen.getByRole('button', { name: 'Confirmar revisión (sin guardar)' }))
    expect(progress()).toBe(5)
    await selectMetabolicMethod(user)
    expect(screen.getByText('1,597.5 kcal/día')).toBeTruthy()
    await user.click(screen.getByRole('button', { name: 'Ver reporte de antropometría' }))
    let dialog = await screen.findByRole('dialog')
    expect(dialog.textContent).toContain('Paciente ficticio')
    expect(dialog.textContent).toContain('SIN GUARDAR')
    await user.click(within(dialog).getByRole('button', { name: 'Volver a fórmulas' }))
    await user.click(screen.getByRole('button', { name: 'Ver reporte alimentario (R24)' }))
    dialog = await screen.findByRole('dialog')
    expect(dialog.textContent).toContain('Recordatorio no realizado')
    expect(dialog.textContent).toContain('no dieta prescrita')
    await user.click(within(dialog).getByRole('button', { name: 'Volver a fórmulas' }))
    await user.click(screen.getByRole('button', { name: 'Ver reporte completo de evaluación' }))
    dialog = await screen.findByRole('dialog')
    expect(dialog.textContent).toContain('Reporte de evaluación')
    expect(dialog.textContent).toContain('Bioquímica')
    expect(dialog.textContent).toContain('Estudio no realizado')
    expect(dialog.textContent).toContain('Paciente ficticio')
    await user.click(within(dialog).getByRole('button', { name: 'Volver a fórmulas' }))
    await user.click(screen.getByRole('button', { name: 'Confirmar revisión (sin guardar)' }))
    expect(progress()).toBe(6)
    expect(screen.getByText(/Seis secciones revisadas en demostración/)).toBeTruthy()
    const nav = screen.getByRole('navigation', { name: 'Secciones de la evaluación inicial' })
    await user.click(within(nav).getByRole('button', { name: /Hábitos/ }))
    expect((screen.getByLabelText('Horas de sueño por día') as HTMLInputElement).value).toBe('7')
    fireEvent.change(screen.getByLabelText('Horas de sueño por día'), { target: { value: '8' } })
    expect(progress()).toBe(4)
    expect((within(nav).getByRole('button', { name: /Fórmulas y reportes/ }) as HTMLButtonElement).disabled).toBe(true)
    await user.click(screen.getByRole('button', { name: 'Continuar' }))
    expect(progress()).toBe(5)
    expect(screen.getByRole('combobox', { name: 'Autor de metabolismo basal / reposo' }).textContent).toContain('Mifflin')
    await user.click(screen.getByRole('button', { name: 'Confirmar revisión (sin guardar)' }))
    expect(progress()).toBe(6)
    await user.click(within(nav).getByRole('button', { name: /Antropometría/ }))
    fireEvent.change(screen.getByLabelText('Peso (kg)'), { target: { value: '72' } })
    expect(progress()).toBe(1)
    await user.click(screen.getByRole('button', { name: 'Continuar' }))
    await user.click(screen.getByRole('button', { name: 'Completar sección' }))
    await user.click(screen.getByRole('button', { name: 'Completar R24' }))
    await user.click(screen.getByRole('button', { name: 'Continuar' }))
    expect(screen.getByText('1,617.5 kcal/día')).toBeTruthy()
  }, 25000)

  it('reutiliza Hábitos y Fórmulas en consulta y comienza sin copiar datos previos', async () => {
    const user = userEvent.setup()
    render(<MemoryRouter initialEntries={['/dashboard/pacientes/DEMO-001/consultas/nueva']}><Routes><Route path="/dashboard/pacientes/:patientId/consultas/nueva" element={<ConsultationRegistration />} /></Routes></MemoryRouter>)
    expect(document.querySelectorAll('form form')).toHaveLength(0)
    await consultationToRecall(user)
    await consultationSkipRecall(user)
    await selectOption(user, 'Disponibilidad de hábitos', 'Capturar entrevista de hábitos')
    await selectOption(user, 'Disponibilidad de actividad física', 'Sin actividad física (declarado)')
    fireEvent.change(screen.getByLabelText('Alimentos que prefiere'), { target: { value: 'Preferencia ficticia' } })
    await user.click(screen.getByRole('button', { name: 'Continuar' }))
    await selectMetabolicMethod(user)
    await user.click(screen.getByRole('button', { name: 'Revisar consulta' }))
    const dialog = await screen.findByRole('dialog')
    expect(dialog.textContent).toContain('Preferencia ficticia')
    expect(within(dialog).getAllByRole('region', { name: 'Resultados de fórmulas' }).some(region => region.textContent?.includes('kcal/día'))).toBe(true)
    expect(dialog.textContent).toContain('no se ha guardado ni enviado')
    await user.click(within(dialog).getByRole('button', { name: 'Volver al formulario' }))
    expect((screen.getByLabelText('Alimentos que prefiere') as HTMLTextAreaElement).value).toBe('Preferencia ficticia')
  }, 15000)
})
