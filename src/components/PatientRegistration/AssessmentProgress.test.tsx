import { afterEach, describe, expect, it } from 'vitest'
import { cleanup, fireEvent, render, screen, within } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import { MemoryRouter } from 'react-router-dom'
import PatientRegistration from './PatientRegistration'
import { continueToAnthropometry, continueToBiochemistry } from './assessmentTestHelpers'
import { canSelectAssessmentStep, invalidateAssessmentStep } from './assessmentProgress'
import { selectRecallOption } from '../DietaryRecall/recallTestHelpers'

afterEach(cleanup)
const renderAssessment = () => render(<MemoryRouter><PatientRegistration /></MemoryRouter>)
const progress = () => screen.getByRole('progressbar', { name: 'Secciones completadas' }) as HTMLProgressElement
const navButton = (label: string) => within(screen.getByRole('navigation', { name: 'Secciones de la evaluación inicial' })).getByRole('button', { name: new RegExp(label) }) as HTMLButtonElement

describe('Progreso y bloqueo secuencial', () => {
  it('bloquea saltos y valida los datos esenciales antes de continuar, enfocando el primer error', async () => {
    const user = userEvent.setup()
    renderAssessment()
    expect(progress().value).toBe(0)
    expect(progress().max).toBe(6)
    expect(navButton('Antropometría').disabled).toBe(true)
    expect(navButton('Bioquímica').disabled).toBe(true)
    await user.click(screen.getByRole('button', { name: 'Continuar' }))
    expect(document.activeElement).toBe(screen.getByLabelText('Nombre completo'))
    expect(progress().value).toBe(0)
    await continueToAnthropometry(user)
    expect(progress().value).toBe(1)
    expect(navButton('Bioquímica').disabled).toBe(true)
    await user.click(screen.getByRole('button', { name: 'Continuar' }))
    expect(document.activeElement).toBe(screen.getByLabelText('Talla (cm)'))
    expect(screen.getByRole('heading', { name: 'Antropometría', level: 2 })).toBeTruthy()
    expect(progress().value).toBe(1)
    fireEvent.change(screen.getByLabelText('Talla (cm)'), { target: { value: '170' } })
    fireEvent.change(screen.getByLabelText('Peso (kg)'), { target: { value: '70' } })
    await user.click(screen.getByRole('button', { name: 'Continuar' }))
    expect(screen.getByRole('heading', { name: 'Bioquímica', level: 2 })).toBeTruthy()
    expect(progress().value).toBe(2)
    expect(screen.queryByRole('dialog')).toBeNull()
  })

  it('no exige todos los pliegues ni todos los análisis y habilita Hábitos solo tras confirmar R24', async () => {
    const user = userEvent.setup()
    renderAssessment()
    await continueToBiochemistry(user)
    await user.click(screen.getByRole('button', { name: 'Completar sección' }))
    expect(progress().value).toBe(2)
    expect(await screen.findByText(/Captura al menos un resultado o indica/)).toBeTruthy()
    expect(document.activeElement).toBe(screen.getByRole('combobox', { name: 'Disponibilidad del estudio' }))
    fireEvent.change(screen.getByLabelText('Valor · Albúmina en suero'), { target: { value: '4.2' } })
    fireEvent.change(screen.getByLabelText('Unidad · Albúmina en suero'), { target: { value: 'g/dL' } })
    await user.click(screen.getByRole('button', { name: 'Completar sección' }))
    expect(progress().value).toBe(3)
    expect(navButton('Recordatorio de 24 horas').disabled).toBe(false)
    expect(navButton('Hábitos').disabled).toBe(true)
    expect(navButton('Fórmulas y reportes').disabled).toBe(true)
    await selectRecallOption(user, 'Disponibilidad del recordatorio', 'Recordatorio no realizado')
    await user.click(screen.getByRole('button', { name: 'Completar R24' }))
    expect(progress().value).toBe(4)
    expect(navButton('Hábitos').disabled).toBe(false)
    expect(screen.getByRole('heading', { name: 'Hábitos', level: 2 })).toBeTruthy()
    expect(navButton('Fórmulas y reportes').disabled).toBe(true)
    await user.click(navButton('Recordatorio de 24 horas'))
    await user.click(screen.getByRole('button', { name: 'Completar R24' }))
    expect(progress().value).toBe(4)
  })

  it('permite volver, conserva captura y revoca los pasos posteriores al editar uno completado', async () => {
    const user = userEvent.setup()
    renderAssessment()
    await continueToBiochemistry(user)
    fireEvent.change(screen.getByLabelText('Valor · Glucosa en plasma'), { target: { value: '95' } })
    fireEvent.change(screen.getByLabelText('Unidad · Glucosa en plasma'), { target: { value: 'mg/dL' } })
    await user.click(screen.getByRole('button', { name: 'Completar sección' }))
    expect(progress().value).toBe(3)
    await user.click(navButton('Antropometría'))
    expect((screen.getByLabelText('Peso (kg)') as HTMLInputElement).value).toBe('70')
    fireEvent.change(screen.getByLabelText('Peso (kg)'), { target: { value: '' } })
    expect(progress().value).toBe(1)
    expect(navButton('Bioquímica').disabled).toBe(true)
    await user.click(screen.getByRole('button', { name: 'Continuar' }))
    expect(document.activeElement).toBe(screen.getByLabelText('Peso (kg)'))
    fireEvent.change(screen.getByLabelText('Peso (kg)'), { target: { value: '72' } })
    await user.click(screen.getByRole('button', { name: 'Continuar' }))
    expect((screen.getByLabelText('Valor · Glucosa en plasma') as HTMLInputElement).value).toBe('95')
    expect(progress().value).toBe(2)
    await user.click(navButton('Datos del paciente'))
    fireEvent.change(screen.getByLabelText('Nombre completo'), { target: { value: '' } })
    expect(progress().value).toBe(0)
    expect(navButton('Antropometría').disabled).toBe(true)
    expect(navButton('Bioquímica').disabled).toBe(true)
  })

  it('permite declarar mediciones y estudios ausentes, sin cálculos ni resultados viejos y sin borrar el borrador', async () => {
    const user = userEvent.setup()
    renderAssessment()
    await continueToAnthropometry(user)
    fireEvent.change(screen.getByLabelText('Talla (cm)'), { target: { value: '170' } })
    fireEvent.change(screen.getByLabelText('Peso (kg)'), { target: { value: '-5' } })
    await user.click(screen.getByRole('button', { name: 'Continuar' }))
    await user.click(screen.getByRole('combobox', { name: 'Disponibilidad de mediciones' }))
    await user.click(screen.getByRole('option', { name: 'Mediciones no disponibles' }))
    expect(screen.queryByRole('region', { name: 'IMC' })).toBeNull()
    await user.click(screen.getByRole('button', { name: 'Continuar' }))
    expect(screen.getByRole('heading', { name: 'Bioquímica', level: 2 })).toBeTruthy()
    fireEvent.change(screen.getByLabelText('Valor · Glucosa en plasma'), { target: { value: '-95' } })
    await user.click(screen.getByRole('button', { name: 'Completar sección' }))
    await user.click(screen.getByRole('combobox', { name: 'Disponibilidad del estudio' }))
    await user.click(screen.getByRole('option', { name: 'Estudio no realizado' }))
    await user.click(screen.getByRole('button', { name: 'Completar sección' }))
    expect([...document.querySelectorAll('[aria-invalid="true"]')].map(element => element.id)).toEqual([])
    expect(progress().value).toBe(3)
    await user.click(navButton('Bioquímica'))
    await user.click(screen.getByRole('button', { name: 'Revisar bioquímica' }))
    const dialog = await screen.findByRole('dialog')
    expect(within(dialog).getByText(/Estudio no realizado/)).toBeTruthy()
    expect(within(dialog).queryByText('-95')).toBeNull()
    await user.click(within(dialog).getByRole('button', { name: 'Volver a bioquímica' }))
    await user.click(screen.getByRole('combobox', { name: 'Disponibilidad del estudio' }))
    await user.click(screen.getByRole('option', { name: 'Capturar resultados' }))
    expect((screen.getByLabelText('Valor · Glucosa en plasma') as HTMLInputElement).value).toBe('-95')
    expect(progress().value).toBe(2)
  })

  it('protege la selección por lógica además de deshabilitar los botones', () => {
    expect(canSelectAssessmentStep('anthropometry', [])).toBe(false)
    expect(canSelectAssessmentStep('biochemistry', ['patient'])).toBe(false)
    expect(canSelectAssessmentStep('biochemistry', ['patient', 'anthropometry'])).toBe(true)
    expect(canSelectAssessmentStep('recall', ['patient', 'anthropometry', 'biochemistry'])).toBe(true)
    expect(canSelectAssessmentStep('habits', ['patient', 'anthropometry', 'biochemistry', 'recall'])).toBe(true)
    expect(canSelectAssessmentStep('reports', ['patient', 'anthropometry', 'biochemistry', 'recall'])).toBe(false)
    expect(invalidateAssessmentStep('anthropometry', ['patient', 'anthropometry', 'biochemistry'])).toEqual(['patient'])
  })
})
